package Plugins::ZXTune::Settings;

use strict;
use warnings;
use base qw(Slim::Web::Settings);

use Slim::Utils::Prefs;
use Slim::Utils::Log;

my $prefs = preferences('plugin.zxtune');
my $log   = logger('plugin.zxtune');

my %DEFAULTS = (
    local_music_dir   => '',
    samplerate        => 48000,
    loopmode          => 0,
    default_duration  => 180,
    aym_type          => 0,
    aym_clockrate     => 1773400,
    aym_layout        => 0,
    aym_interpolation => 2,
    aym_table         => '',
    aym_duty_cycle    => 50,
    dac_interpolation => 1,
    fm_clockrate      => 3500000,
    saa_clockrate     => 8000000,
    saa_interpolation => 2,
    unpack_archives   => 1,
    auto_online_cover => 1,
    modarchive_key    => '',
    cache_max_mb      => 256,
);

sub init {
    my $class = shift;
    $prefs->init(\%DEFAULTS);
    $class->writeZXTuneConfig();
}

sub name {
    return Slim::Web::HTTP::CSRF->protectName('PLUGIN_ZXTUNE');
}

sub page {
    return Slim::Web::HTTP::CSRF->protectURI('plugins/ZXTune/settings/basic.html');
}

sub prefs {
    return (
        $prefs,
        qw(
            local_music_dir
            samplerate
            loopmode
            default_duration
            aym_type
            aym_clockrate
            aym_layout
            aym_interpolation
            aym_table
            aym_duty_cycle
            dac_interpolation
            fm_clockrate
            saa_clockrate
            saa_interpolation
            unpack_archives
            auto_online_cover
            modarchive_key
            cache_max_mb
        )
    );
}

sub handler {
    my ($class, $client, $params, $callback, @args) = @_;
    my $ret = $class->SUPER::handler($client, $params, $callback, @args);
    if ($params->{saveSettings}) {
        $class->writeZXTuneConfig();
    }
    return $ret;
}

sub writeZXTuneConfig {
    my $class = shift;
    my $confFile = '/tmp/zxtune_lms.conf';

    my $freq      = int($prefs->get('samplerate')        || 48000);
    my $loop      = int($prefs->get('loopmode')          || 0);
    my $defDurSec = int($prefs->get('default_duration')  || 180);
    my $ayFrames  = $defDurSec * 50;
    my $aymType   = int($prefs->get('aym_type')          || 0);
    my $aymClock  = int($prefs->get('aym_clockrate')     || 1773400);
    my $aymLayout = int($prefs->get('aym_layout')        || 0);
    my $aymInterp = int($prefs->get('aym_interpolation') // 2);
    my $aymTable  = $prefs->get('aym_table')             || '';
    my $aymDuty   = int($prefs->get('aym_duty_cycle')    || 50);
    my $dacInterp = int($prefs->get('dac_interpolation') // 1);
    my $fmClock   = int($prefs->get('fm_clockrate')      || 3500000);
    my $saaClock  = int($prefs->get('saa_clockrate')     || 8000000);
    my $saaInterp = int($prefs->get('saa_interpolation') // 2);

    $aymDuty = 50 if $aymDuty < 1 || $aymDuty > 99;

    if (open(my $fh, '>', $confFile)) {
        print $fh "# Generated by Plugins::ZXTune::Settings\n";
        print $fh "zxtune.sound.frequency=$freq\n";
        print $fh "zxtune.sound.loopmode=$loop\n";
        print $fh "zxtune.core.aym.type=$aymType\n";
        print $fh "zxtune.core.aym.clockrate=$aymClock\n";
        print $fh "zxtune.core.aym.layout=$aymLayout\n";
        print $fh "zxtune.core.aym.interpolation=$aymInterp\n";
        if (length $aymTable) {
            print $fh "zxtune.core.aym.table='$aymTable'\n";
        }
        print $fh "zxtune.core.aym.duty_cycle=$aymDuty\n";
        print $fh "zxtune.core.dac.interpolation=$dacInterp\n";
        print $fh "zxtune.core.fm.clockrate=$fmClock\n";
        print $fh "zxtune.core.saa.clockrate=$saaClock\n";
        print $fh "zxtune.core.saa.interpolation=$saaInterp\n";
        print $fh "zxtune.core.plugins.ay.default_duration=$ayFrames\n";
        print $fh "zxtune.core.plugins.hrip.ignore_corrupted=1\n";
        print $fh "zxtune.core.plugins.zip.max_depacked_size_mb=512\n";
        print $fh "zxtune.io.providers.file.overwrite=1\n";
        print $fh "zxtune.io.providers.file.sanitize_names=0\n";
        close($fh);
    } else {
        $log->warn("Could not write $confFile: $!");
    }
}

1;
